/// 非 ASCII 字符的 tofu 方框。
const TOFU_ART: &str = "######...##.#.#..#..#.#.##...######";

fn art_to_cols(art: &str) -> [u8; 5] {
    let mut cols = [0u8; 5];
    let bytes = art.as_bytes();
    debug_assert_eq!(bytes.len(), 35);
    for row in 0..7usize {
        for col in 0..5usize {
            if bytes[row * 5 + col] == b'#' {
                cols[col] |= 1 << row;
            }
        }
    }
    cols
}

struct FallbackFont {
    cols: HashMap<u8, [u8; 5]>,
}

static FONT: OnceLock<FallbackFont> = OnceLock::new();

fn font() -> &'static FallbackFont {
    FONT.get_or_init(|| {
        let mut cols = HashMap::new();
        for (i, art) in GLYPH_ART.iter().enumerate() {
            cols.insert(0x20u8 + i as u8, art_to_cols(art));
        }
        cols.insert(0x7F, art_to_cols(TOFU_ART));
        FallbackFont { cols }
    })
}

/// 缩放倍数：7 行点阵放大到请求字号（20 → 2 倍，26 → 3 倍）。
/// 注意用截断除法而不是四舍五入：20/8=2.5，round 会进到 3（Python 的
/// round(2.5)=2 是银行家舍入，Rust 的 round(2.5)=3 是远离零），20px 档
/// 就变 3 倍（21px 高）了。
fn scale_for(px: u16) -> i32 {
    (px as i32 / 8).max(1)
}

/// 回退字体的基线高度（文本框顶到基线）。
pub(crate) fn ascent(px: u16) -> f32 {
    7.0 * scale_for(px) as f32
}

/// 光栅化一个回退字形（灰度 0/255，无抗锯齿——和点阵屏风格一致）。
pub(crate) fn glyph(px: u16, ch: char) -> GlyphBitmap {
    let s = scale_for(px) as usize;
    let code: u8 = if ch.is_ascii() { ch as u8 } else { 0x7F };
    let cols = font().cols.get(&code).copied().unwrap_or_else(|| art_to_cols(TOFU_ART));
    let w = 5 * s;
    let h = 7 * s;
    let mut data = vec![0u8; w * h];
    for row in 0..7usize {
        for col in 0..5usize {
            if cols[col] & (1 << row) != 0 {
                for dy in 0..s {
                    for dx in 0..s {
                        data[(row * s + dy) * w + col * s + dx] = 255;
                    }
                }
            }
        }
    }
    GlyphBitmap {
        width: w as i32,
        height: h as i32,
        data,
        left: 0,
        top: -(h as i32),
        advance: 6.0 * s as f32,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn art_strings_are_35_chars() {
        for (i, art) in GLYPH_ART.iter().enumerate() {
            assert_eq!(art.len(), 35, "点阵画稿必须 35 字符 (#{})", i);
        }
        assert_eq!(TOFU_ART.len(), 35);
    }

    #[test]
    fn glyph_count_covers_ascii() {
        assert_eq!(GLYPH_ART.len(), 95); // 0x20..=0x7E
    }

    #[test]
    fn shapes_sanity() {
        // 'I'：上下横（0x41 = 行0/6）+ 中列全实（0x7F）
        let i = font().cols.get(&b'I').copied().unwrap();
        assert_eq!(i, [0x00, 0x41, 0x7F, 0x41, 0x00]);
        // '|'：中列全实、其余空
        let bar = font().cols.get(&b'|').copied().unwrap();
        assert_eq!(bar, [0x00, 0x00, 0x7F, 0x00, 0x00]);
        // ' '：无笔画
        let sp = font().cols.get(&b' ').copied().unwrap();
        assert_eq!(sp, [0; 5]);
        // 'H'：两列全高（0x7F）+ 中横在行3（0x08）
        let h = font().cols.get(&b'H').copied().unwrap();
        assert_eq!(h, [0x7F, 0x08, 0x08, 0x08, 0x7F]);
        // 'A'：两侧行1-6（0x7E）+ 顶横/中横（0x09 = 行0/3）
        let a = font().cols.get(&b'A').copied().unwrap();
        assert_eq!(a, [0x7E, 0x09, 0x09, 0x09, 0x7E]);
    }

    #[test]
    fn scaled_metrics() {
        let g20 = glyph(20, 'A');
        assert_eq!(g20.width, 10);
        assert_eq!(g20.height, 14);
        assert_eq!(g20.advance, 12.0);
        assert_eq!(g20.top, -14);
        let g26 = glyph(26, 'A');
        assert_eq!(g26.width, 15);
        assert_eq!(g26.height, 21);
        assert_eq!(ascent(26), 21.0);
        // 非 ASCII → tofu 方框
        let t = glyph(20, '中');
        assert!(t.width > 0 && t.height > 0);
    }
}
