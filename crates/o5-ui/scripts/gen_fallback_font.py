TOFU = ["#####", "#...#", "#.#.#", "..#..", "#.#.#", "#...#", "#####"]


def validate():
    chars = [chr(c) for c in range(0x20, 0x7F)]
    assert sorted(G.keys()) == sorted(chars), (
        "missing: %r extra: %r" % (set(chars) - set(G), set(G) - set(chars))
    )
    for ch, rows in G.items():
        assert len(rows) == 7, (ch, len(rows))
        for r in rows:
            assert len(r) == 5, (ch, repr(r))
            assert set(r) <= {"#", "."}, (ch, repr(r))
    assert len(TOFU) == 7 and all(len(r) == 5 for r in TOFU)


def show():
    # Print in rows of 8 glyphs for visual review
    chars = [chr(c) for c in range(0x20, 0x7F)]
    for base in range(0, len(chars), 8):
        chunk = chars[base : base + 8]
        print("  ".join("%-5s" % c for c in chunk))
        for row in range(7):
            print("  ".join(G[c][row] for c in chunk))
        print()


def flat(rows):
    return "".join(rows)


def emit():
    out = []
    out.append("const GLYPH_ART: [&str; 95] = [")
    for c in range(0x20, 0x7F):
        ch = chr(c)
        cmt = ch.replace("\\", "\\\\").replace("'", "\\'")
        out.append('    // \'%s\'' % cmt)
        out.append('    "%s",' % flat(G[ch]))
    out.append("];")
    print("\n".join(out))
    print()
    print('const TOFU_ART: &str = "%s";' % flat(TOFU))


def cols(rows):
    col = [0] * 5
    for r, row in enumerate(rows):
        for c, ch in enumerate(row):
            if ch == "#":
                col[c] |= 1 << r
    return col


